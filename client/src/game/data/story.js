// current: 지금 미션 id, started: 그 미션을 맡았는지, giver: 미션을 맡길 NPC id, ribbons: 모은 리본 수
export function chiefHintLines({ current, started, giver, ribbons }) {
  if (!current) return STORY.final.after;
  const head = ribbons ? `감사 리본 ${ribbons}개를 모았구나. 앞으로 ${5 - ribbons}개 남았어!` : '감사 리본 5개를 모으러 출발해 볼까?';
  if (!started) return [head, `지금은 ${NPCS[giver].where}에게 가 보렴. 머리 위에 ❗ 가 떠 있을 게다.`];
  return [head, QUEST_HINTS[current], '발밑의 노란 화살표를 따라가면 길을 잃지 않는단다.'];
}
