export function chiefHintLines(progress) {
  const done = progress.completed;
  if (done.includes('final')) {
    return ['덕분에 멋진 축제가 열렸구나. 정말 고맙다!', '밥 한 그릇에 담긴 농부님들의 땀과 정성, 잊지 말거라. 🍚'];
  }
  const left = MAIN_QUESTS.filter((q) => !done.includes(q));
  if (!left.length) {
    return ['감사 리본 5개를 모두 모았구나! 🎀', '광장 서쪽의 커다란 당산나무에 리본을 매달아 축제를 열어 다오!'];
  }
  return [
    left.length === 5 ? '감사 리본 5개를 모으러 출발해 볼까? 내가 하나 알려 주마.' : `감사 리본 ${5 - left.length}개를 모았구나. 앞으로 ${left.length}개 남았어!`,
    QUEST_HINTS[left[0]],
    '다른 미션부터 해도 괜찮단다. 왼쪽 위 미션 창과 노란 화살표를 잘 보렴.',
  ];
}
